import { strict as assert } from 'node:assert';
import { EditorState, EditorSelection, Transaction } from '@codemirror/state';
import { taskSortingExtension } from './editor-sorting';
const text = '## TODO\n- [ ] A\n  - [x] Child\n- [ ] B\n\n## Meetings\n';
const state = EditorState.create({ doc: text, selection: EditorSelection.cursor(text.indexOf('A') + 1), extensions: [taskSortingExtension(() => true)] });
const pos = text.indexOf('[ ]') + 1;
const tr = state.update({ changes: { from: pos, to: pos + 1, insert: 'x' }, userEvent: 'input' });
const result = tr.newDoc.toString();
assert.ok(result.includes('> [!done]- Completed\n> - [x] A\n>   - [x] Child'));
assert.equal(result[tr.newSelection.main.head - 1], 'A', 'cursor follows the moved task');
const undo = tr.state.update({ changes: { from: 0, to: tr.newDoc.length, insert: text }, userEvent: 'undo' });
assert.equal(undo.newDoc.toString(), text, 'undo restores the original layout');
const redo = undo.state.update({ changes: { from: 0, to: undo.newDoc.length, insert: result }, userEvent: 'redo' });
assert.equal(redo.newDoc.toString(), result);
const unrelated = state.update({ changes: { from: text.indexOf('A'), to: text.indexOf('A') + 1, insert: 'Edited' } });
assert.equal(unrelated.newDoc.toString(), text.replace('A', 'Edited'));
const disabled = EditorState.create({ doc: text, extensions: [taskSortingExtension(() => false)] });
assert.equal(disabled.update({ changes: { from: pos, to: pos + 1, insert: 'x' } }).newDoc.toString(), text.replace('[ ] A', '[x] A'));
assert.equal(state.update({ changes: { from: pos, to: pos + 1, insert: 'x' }, annotations: Transaction.remote.of(true) }).newDoc.toString(), text.replace('[ ] A', '[x] A'));
console.log('Editor transaction tests passed.');

// Exercise the real CodeMirror history, including the filter during undo/redo.
const { history, undo: undoCommand, redo: redoCommand, undoDepth } = await import('@codemirror/commands');
let current = EditorState.create({ doc: text, selection: EditorSelection.cursor(text.indexOf('A') + 1), extensions: [history(), taskSortingExtension(() => true)] });
current = current.update({ changes: { from: pos, to: pos + 1, insert: 'x' }, userEvent: 'input' }).state;
const sortedText = current.doc.toString();
assert.equal(undoDepth(current), 1, 'checking plus sorting creates exactly one undo step');
const dispatch = (tr: Transaction) => { current = tr.state; };
assert.ok(undoCommand({ state: current, dispatch }));
assert.equal(current.doc.toString(), text);
assert.equal(current.selection.main.head, text.indexOf('A') + 1);
assert.ok(redoCommand({ state: current, dispatch }));
assert.equal(current.doc.toString(), sortedText);
const activeState = current;
const checkedPos = current.doc.toString().indexOf('> - [x] A') + 5;
current = current.update({ changes: { from: checkedPos, to: checkedPos + 1, insert: ' ' }, annotations: Transaction.time.of(Date.now() + 1000), userEvent: 'input' }).state;
assert.ok(current.doc.toString().includes('- [ ] B\n- [ ] A\n  - [x] Child'));
assert.ok(undoCommand({ state: current, dispatch }));
assert.equal(current.doc.toString(), activeState.doc.toString());
assert.ok(redoCommand({ state: current, dispatch }));
assert.ok(current.doc.toString().includes('- [ ] B\n- [ ] A'));
console.log('Real undo/redo history tests passed.');

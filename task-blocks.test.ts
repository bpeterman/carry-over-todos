import { strict as assert } from 'node:assert';
import { insertTaskBlocks, openTaskBlocks, removeOpenTaskBlocks, sortCheckboxChanges } from './task-blocks';
const note = (s: string) => '# Daily\n\n## TODO\n\n' + s + '\n\n## Meetings\n- [ ] Meeting\n\n## Notes\nKeep me\n';
function toggle(before: string, from: string, to: string) {
  const after = before.replace(from, to);
  return sortCheckboxChanges(before, after)?.text ?? after;
}
const block = '- [ ] Parent [[link]]\n\t- [x] Done child\n\t  detail [link](url)\n\t- [ ] Open child\n\t\t- [x] Deep\n  Parent note';
const before = note(block + '\n- [ ] Second');
const completed = toggle(before, '- [ ] Parent', '- [x] Parent');
assert.equal(completed, note('- [ ] Second\n\n> [!done]- Completed\n' + block.replace('- [ ] Parent', '- [x] Parent').split('\n').map(s => '> ' + s).join('\n')));
assert.equal(toggle(completed, '> - [x] Parent', '> - [ ] Parent'), note('- [ ] Second\n' + block + '\n\n> [!done]- Completed'));
const nested = note('- [ ] P\n  - [ ] A\n    - [ ] Deep A\n    note A\n  - [ ] B\n  - [x] C\n- [ ] Q');
assert.equal(toggle(nested, '- [ ] A', '- [x] A'), note('- [ ] P\n  - [ ] B\n  - [x] C\n  - [x] A\n    - [ ] Deep A\n    note A\n- [ ] Q'));
assert.equal(toggle(nested, '- [x] C', '- [ ] C'), note('- [ ] P\n  - [ ] A\n    - [ ] Deep A\n    note A\n  - [ ] B\n  - [ ] C\n- [ ] Q'));
const deep = note('- [ ] P\n\t- [ ] A\n\t\t- [ ] One\n\t\t  details\n\t\t- [ ] Two\n\t- [ ] B');
assert.equal(toggle(deep, '- [ ] One', '- [x] One'), note('- [ ] P\n\t- [ ] A\n\t\t- [ ] Two\n\t\t- [x] One\n\t\t  details\n\t- [ ] B'));
const callout = note('- [ ] Active\n\n> [!done]- Completed\n> - [x] Old\n>   - [ ] A\n>     notes\n>   - [ ] B\n> - [x] Other');
assert.equal(toggle(callout, '>   - [ ] A', '>   - [x] A'), note('- [ ] Active\n\n> [!done]- Completed\n> - [x] Old\n>   - [ ] B\n>   - [x] A\n>     notes\n> - [x] Other'));
assert.equal(toggle(callout, '> - [x] Old', '> - [ ] Old'), note('- [ ] Active\n- [ ] Old\n  - [ ] A\n    notes\n  - [ ] B\n\n> [!done]- Completed\n> - [x] Other'));
assert.equal(toggle(callout, '- [ ] Active', '- [x] Active'), note('\n> [!done]- Completed\n> - [x] Old\n>   - [ ] A\n>     notes\n>   - [ ] B\n> - [x] Other\n> - [x] Active'));
const mixed = note('- [ ] P\n\t- [ ] First\n    - [ ] Second\n\t- [ ] Third');
assert.equal(toggle(mixed, '- [ ] First', '- [x] First'), note('- [ ] P\n    - [ ] Second\n\t- [ ] Third\n\t- [x] First'));
assert.equal(sortCheckboxChanges(before, before.replace('Second', 'Edited')), undefined);
assert.equal(sortCheckboxChanges(before, before.replace('- [ ] Meeting', '- [x] Meeting')), undefined);
assert.equal(sortCheckboxChanges(before, before.replace('- [ ] Parent', '- [x] Changed')), undefined);
for (const code of ['```md\n- [ ] Example\n```', '~~~\n- [ ] Example\n~~~', '    - [ ] Example']) {
  const n = note(code + '\n- [ ] Real');
  assert.equal(sortCheckboxChanges(n, n.replace('- [ ] Example', '- [x] Example')), undefined);
}
const inside = note('- [ ] P\n  ```md\n  - [ ] Example\n  ```\n  - [ ] Actual');
assert.equal(sortCheckboxChanges(inside, inside.replace('- [ ] Example', '- [x] Example')), undefined);
const fakeSection = '```\n## TODO\n- [ ] Fake\n```\n## Notes\n- [ ] Other';
assert.equal(sortCheckboxChanges(fakeSection, fakeSection.replace('[ ] Fake', '[x] Fake')), undefined);
assert.deepEqual(openTaskBlocks(completed), [['- [ ] Second']]);
assert.deepEqual(openTaskBlocks(before), [block.split('\n'), ['- [ ] Second']]);
const removed = removeOpenTaskBlocks(before, openTaskBlocks(before));
assert.equal(openTaskBlocks(removed).length, 0);
assert.ok(removed.endsWith('## Meetings\n- [ ] Meeting\n\n## Notes\nKeep me\n'));
assert.equal(insertTaskBlocks(note('- [ ] Number 1'), [block.split('\n')]), note(block));
assert.equal(insertTaskBlocks(callout, [block.split('\n')]), callout.replace('- [ ] Active', '- [ ] Active\n' + block));
assert.equal(removeOpenTaskBlocks(before.replace('Parent note', 'Edited note'), openTaskBlocks(before)), before.replace('Parent note', 'Edited note').replace('- [ ] Second\n', ''));
assert.equal(insertTaskBlocks('## Notes\n', [['- [ ] Task']]), undefined);
const crlf = before.replace(/\n/g, '\r\n');
assert.equal(toggle(crlf, '- [ ] Parent', '- [x] Parent'), completed.replace(/\n/g, '\r\n'));
const changed = before.replace('- [ ] Parent', '- [x] Parent');
const sorted = sortCheckboxChanges(before, changed)!;
assert.equal(sorted.text.slice(sorted.mapOffset(changed.indexOf('Parent [[link]]'))).split('\n')[0], 'Parent [[link]]');
console.log('Task-block tests passed.');

const notesBetween = note('- [ ] Parent\n  - supporting note\n  - [ ] A\n  - [ ] B');
assert.equal(toggle(notesBetween, '- [ ] A', '- [x] A'), note('- [ ] Parent\n  - supporting note\n  - [ ] B\n  - [x] A'));
const plainParent = note('- [ ] Parent\n  - a normal list parent\n    - [ ] A\n    - [ ] B\n  - [ ] Separate');
assert.equal(toggle(plainParent, '- [ ] A', '- [x] A'), note('- [ ] Parent\n  - a normal list parent\n    - [ ] B\n    - [x] A\n  - [ ] Separate'));
const lazy = note('- [ ] Parent\nlazy continuation\n  - [ ] A\n  - [ ] B');
assert.equal(toggle(lazy, '- [ ] A', '- [x] A'), note('- [ ] Parent\nlazy continuation\n  - [ ] B\n  - [x] A'));
const comment = note('<!--\n- [ ] Hidden\n-->\n- [ ] Visible <!-- task metadata -->');
assert.equal(sortCheckboxChanges(comment, comment.replace('[ ] Hidden', '[x] Hidden')), undefined);
assert.deepEqual(openTaskBlocks(comment), [['- [ ] Visible <!-- task metadata -->']]);
const unchecked = note('- [ ] Parent\n  - [ ] A\n  - [x] B\n    - [x] B child\n  - [x] C');
assert.equal(toggle(unchecked, '- [x] C', '- [ ] C'), note('- [ ] Parent\n  - [ ] A\n  - [ ] C\n  - [x] B\n    - [x] B child'));
const multiple = note('- [ ] A\n  - [ ] child A\n- [ ] B\n- [ ] C');
const multi = sortCheckboxChanges(multiple, multiple.replace('[ ] A', '[x] A').replace('[ ] B', '[x] B'))!.text;
assert.ok(multi.includes('- [ ] C\n\n> [!done]- Completed\n> - [x] A\n>   - [ ] child A\n> - [x] B'));
const adjacentCallout = note('- [ ] Active\n\n> [!done]- Completed\n> - [x] Done\n>\n> [!note] Other callout\n> Do not move');
const restored = toggle(adjacentCallout, '> - [x] Done', '> - [ ] Done');
assert.ok(restored.includes('- [ ] Active\n- [ ] Done'));
assert.ok(restored.includes('> [!note] Other callout\n> Do not move'));
assert.ok(!restored.includes('- [ ] Done\n[!note]'));
